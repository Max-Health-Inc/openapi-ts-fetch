"""Spec loading, validation, and the write pass that lays out the client on disk."""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path

from .apis import gen_api
from .models import gen_enum_model, gen_model, model_refs
from .naming import camel, operation_id, pascal
from .schema_registry import SchemaRegistry, norm_type
from .version import __version__

# ─── Output header ─────────────────────────────────────────────────────────────

HEADER_TPL = """/* tslint:disable */
/* eslint-disable */
/**
 * {title}
 * {description}
 *
 * The version of the OpenAPI document: {version}
 *
 * NOTE: This class is auto generated by openapi-ts-fetch
 * Do not edit the class manually.
 */
"""


def _collect_model_deps(name: str, registry: SchemaRegistry, visited: set[str] | None = None) -> set[str]:
    """Transitively collect all model names referenced by *name*."""
    if visited is None:
        visited = set()
    if name in visited or name not in registry.models:
        return visited
    visited.add(name)
    schema = registry.models[name]
    props = schema.get("properties", {})
    if not isinstance(props, dict):
        return visited
    for pschema in props.values():
        ts = registry.ts_type(pschema, "")
        for dep in model_refs(ts, registry, name):
            _collect_model_deps(dep, registry, visited)
    return visited


def generate(
    spec_path: str,
    output_dir: str,
    tag_filter: set[str] | None = None,
    base_path_override: str | None = None,
    dry_run: bool = False,
):
    """Main entry: read spec, walk operations, generate files.

    If *tag_filter* is provided, only API classes whose tag (case-insensitive)
    is in the set are generated.  Models are pruned to those transitively
    referenced by the selected APIs.
    """
    # Load spec from URL or local file
    if spec_path.startswith(("http://", "https://")):
        print(f"[fetch] {spec_path}")
        req = urllib.request.Request(spec_path, headers={"User-Agent": f"openapi-ts-fetch/{__version__}"})
        with urllib.request.urlopen(req) as resp:  # noqa: S310
            raw = resp.read().decode("utf-8")
        if spec_path.endswith((".yaml", ".yml")):
            import yaml

            spec = yaml.safe_load(raw)
        else:
            spec = json.loads(raw)
    else:
        with open(spec_path, encoding="utf-8") as f:
            if spec_path.endswith((".yaml", ".yml")):
                import yaml

                spec = yaml.safe_load(f)
            else:
                spec = json.load(f)

    # Validate minimal spec structure
    if not isinstance(spec, dict) or "openapi" not in spec:
        print("[ERROR] Input does not look like a valid OpenAPI 3.x spec (missing 'openapi' key)")
        sys.exit(1)
    openapi_ver = spec["openapi"]
    if not str(openapi_ver).startswith("3."):
        print(f"[ERROR] Only OpenAPI 3.x is supported (found '{openapi_ver}')")
        sys.exit(1)
    if "paths" not in spec and "webhooks" not in spec:
        print("[ERROR] Spec has no 'paths' or 'webhooks' — nothing to generate")
        sys.exit(1)

    info = spec.get("info", {})
    title = info.get("title", "API")
    description = info.get("description", "")
    version = info.get("version", "0.0.0")
    base_path = base_path_override if base_path_override is not None else ""

    # Dry-run: just validate and report what would be generated
    if dry_run:
        tags_in_spec: set[str] = set()
        for _path, path_item in (spec.get("paths", {}) or {}).items():
            if not isinstance(path_item, dict):
                continue
            for method in ("get", "post", "put", "patch", "delete", "head", "options"):
                op = path_item.get(method)
                if op and isinstance(op, dict):
                    for t in op.get("tags", ["Default"]):
                        tags_in_spec.add(t)
        schema_count = len(spec.get("components", {}).get("schemas", {}))
        print(f"[dry-run] {title} v{version} (OpenAPI {openapi_ver})")
        print(f"[dry-run] Tags: {', '.join(sorted(tags_in_spec)) or 'none'}")
        print(f"[dry-run] Schemas: {schema_count}")
        if tag_filter:
            missing = tag_filter - {t.lower() for t in tags_in_spec}
            if missing:
                print(f"[dry-run] WARNING: requested tags not in spec: {', '.join(sorted(missing))}")
        return [], []

    header = HEADER_TPL.format(title=title, description=description, version=version)
    registry = SchemaRegistry(spec)

    # ── Phase 1: Walk all operations, extract schemas ────────────────────────
    tag_ops: dict[str, list[dict]] = defaultdict(list)

    for path, path_item in (spec.get("paths", {}) or {}).items():
        if not isinstance(path_item, dict):
            continue
        for method in ("get", "post", "put", "patch", "delete", "head", "options"):
            op = path_item.get(method)
            if not op or not isinstance(op, dict):
                continue

            tags = op.get("tags", ["Default"])
            oid = operation_id(method, path, op)
            op_pascal = pascal(oid)

            # Parameters
            params: list[dict] = []
            refs: set[str] = set()

            raw_params = list(path_item.get("parameters", [])) + list(op.get("parameters", []))
            for p in raw_params:
                if "$ref" in p:
                    _, p = registry.resolve_ref(p["$ref"])
                p_schema = p.get("schema", {})
                ts = registry.ts_type(p_schema, op_pascal + pascal(p.get("name", "")))
                refs |= model_refs(ts, registry)
                params.append(
                    {
                        "name": p.get("name", ""),
                        "in": p.get("in", "query"),
                        "required": p.get("required", False),
                        "ts": ts,
                    }
                )

            # Request body
            req_schema = registry.request_schema(op.get("requestBody"))
            if req_schema:
                ctx = req_schema.get("title")
                if ctx and isinstance(ctx, str):
                    ctx = pascal(ctx)
                else:
                    ctx = op_pascal + "Request"
                ts = registry.ts_type(req_schema, ctx)
                refs |= model_refs(ts, registry)
                body_name = camel(ts.replace(" | null", "").strip()) if ts[0:1].isupper() else "body"
                params.append(
                    {
                        "name": body_name,
                        "in": "body",
                        "required": True,
                        "ts": ts,
                    }
                )

            # Response
            resp_code, resp_schema = registry.response_schema(op.get("responses", {}))
            resp_type = "void"
            resp_array = False
            resp_item = None
            if resp_schema:
                ctx = resp_schema.get("title")
                if ctx and isinstance(ctx, str):
                    ctx = pascal(ctx)
                else:
                    # Match Java convention: OperationId + StatusCode + Response
                    ctx = f"{op_pascal}{resp_code or ''}Response"
                resp_type = registry.ts_type(resp_schema, ctx)
                refs |= model_refs(resp_type, registry)
                resp_type_str, _ = norm_type(resp_schema)
                if resp_type_str == "array":
                    resp_array = True
                    items = resp_schema.get("items", {})
                    item_ctx = items.get("title") if isinstance(items.get("title"), str) else None
                    if item_ctx:
                        item_ctx = pascal(item_ctx)
                    else:
                        item_ctx = f"{op_pascal}{resp_code or ''}ResponseItem"
                    resp_item = registry.ts_type(items, item_ctx)

            op_data = {
                "id": oid,
                "method": method,
                "path": path,
                "summary": op.get("summary", ""),
                "description": op.get("description", ""),
                "params": params,
                "resp_type": resp_type,
                "resp_array": resp_array,
                "resp_item": resp_item,
                "_refs": refs,
            }
            # Assign to first tag only (like Java generator) to avoid
            # duplicate request interface exports across API classes.
            # Deduplicate operations with the same ID within a tag
            # (e.g. FastAPI api_route with multiple methods generates duplicates).
            existing_ids = {o["id"] for o in tag_ops[tags[0]]}
            if oid not in existing_ids:
                tag_ops[tags[0]].append(op_data)

    # ── Tag filtering ────────────────────────────────────────────────────────
    if tag_filter:
        normalized = {t.lower() for t in tag_filter}
        filtered: dict[str, list[dict]] = {}
        for tag, ops in tag_ops.items():
            if tag.lower() in normalized:
                filtered[tag] = ops
        skipped = set(tag_ops) - set(filtered)
        if skipped:
            print(f"   [skip] tags not selected: {', '.join(sorted(skipped))}")
        tag_ops = filtered

    # ── Phase 2: Generate files ──────────────────────────────────────────────
    out = Path(output_dir)
    models_dir = out / "models"
    apis_dir = out / "apis"
    models_dir.mkdir(parents=True, exist_ok=True)
    apis_dir.mkdir(parents=True, exist_ok=True)

    # Determine which models are needed
    if tag_filter:
        needed_models: set[str] = set()
        for ops in tag_ops.values():
            for op in ops:
                needed_models |= op.get("_refs", set())
        # Transitively expand dependencies
        all_needed: set[str] = set()
        for m in needed_models:
            _collect_model_deps(m, registry, all_needed)
    else:
        all_needed = set(registry.models.keys())

    # Models
    model_files: list[str] = []
    enum_files: list[str] = []
    for name, schema in sorted(registry.models.items()):
        if name not in all_needed:
            continue
        # Standalone enum schemas (no properties, just enum values)
        if "enum" in schema and not schema.get("properties"):
            content = gen_enum_model(name, schema, header)
            (models_dir / f"{name}.ts").write_text(content, encoding="utf-8")
            enum_files.append(name)
            print(f"   [ok] models/{name}.ts (enum)")
            continue
        if not schema.get("properties"):
            continue
        content = gen_model(name, schema, registry, header)
        (models_dir / f"{name}.ts").write_text(content, encoding="utf-8")
        model_files.append(name)
        print(f"   [ok] models/{name}.ts")

    # Models index (includes both object models and standalone enums)
    idx = "/* tslint:disable */\n/* eslint-disable */\n"
    for n in sorted(model_files + enum_files):
        idx += f"export * from './{n}';\n"
    (models_dir / "index.ts").write_text(idx, encoding="utf-8")

    # APIs
    api_files: list[str] = []
    total_ops = 0
    for tag, ops in sorted(tag_ops.items()):
        cls = pascal(tag) + "Api"
        content = gen_api(tag, ops, registry, header)
        (apis_dir / f"{cls}.ts").write_text(content, encoding="utf-8")
        api_files.append(cls)
        total_ops += len(ops)
        print(f"   [ok] apis/{cls}.ts ({len(ops)} operations)")

    # APIs index
    idx = "/* tslint:disable */\n/* eslint-disable */\n"
    for n in sorted(api_files):
        idx += f"export * from './{n}';\n"
    (apis_dir / "index.ts").write_text(idx, encoding="utf-8")

    # runtime.ts — copy from template, update BASE_PATH + version
    runtime_path = out / "runtime.ts"
    template_path = Path(__file__).parent / "runtime-template.ts"
    if template_path.exists():
        rt = template_path.read_text(encoding="utf-8")
    elif runtime_path.exists():
        rt = runtime_path.read_text(encoding="utf-8")
    else:
        print("   [ERROR] runtime-template.ts not found next to generator and runtime.ts not found in output!")
        sys.exit(1)
    rt = re.sub(r'export const BASE_PATH = "[^"]*"', f'export const BASE_PATH = "{base_path}"', rt)
    rt = re.sub(r"The version of the OpenAPI document: [^\n]*", f"The version of the OpenAPI document: {version}", rt)
    rt = re.sub(
        r"NOTE: This class is auto generated by OpenAPI Generator.*\n.*openapi-generator\.tech\n.*Do not edit the class manually\.",
        "NOTE: This class is auto generated by openapi-ts-fetch\n * Do not edit the class manually.",
        rt,
    )
    runtime_path.write_text(rt, encoding="utf-8")
    print(f"   [ok] runtime.ts ({'created' if not runtime_path.exists() else 'updated'})")

    # Top-level index.ts
    (out / "index.ts").write_text(
        "/* tslint:disable */\n/* eslint-disable */\nexport * from './runtime';\nexport * from './apis/index';\nexport * from './models/index';\n",
        encoding="utf-8",
    )

    print(f"\n[ok] Generated {len(model_files)} models, {len(api_files)} API classes, {total_ops} operations")
    return model_files, api_files
